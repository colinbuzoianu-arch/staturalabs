// Resolve a system hazard's display name in the given locale, falling back to
// the stored (English) name for EN and for any code not in the map (e.g. a
// tenant's own hazard).
export function resolveHazardName(
  code: string,
  storedName: string,
  locale: Locale,
): string {
  if (locale === "de") return HAZARD_NAME_DE[code] ?? storedName;
  if (locale === "ro") return HAZARD_NAME_RO[code] ?? storedName;
  return storedName;
}

export function resolveEnvironmentalAspectName(
  code: string,
  storedName: string,
  locale: Locale,
): string {
  if (locale === "de") return ENV_ASPECT_NAME_DE[code] ?? storedName;
  if (locale === "ro") return ENV_ASPECT_NAME_RO[code] ?? storedName;
  return storedName;
}
