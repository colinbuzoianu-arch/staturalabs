// One-off generator, not wired into predev/prebuild (unlike fetch-fonts.mjs
// /fetch-pose-model.mjs): transcribes public/logo/statura_logo_on_light.svg
// into a React component built from @react-pdf/renderer's own Svg
// primitives (Path/Circle/Line/G), because react-pdf's <Image> doesn't
// rasterize arbitrary SVG and pulling in a rasterizer (e.g. sharp) just to
// produce one static embedded asset is more moving parts than this needs.
// This SVG is small and flat enough (no gradients/filters/nested transforms
// beyond one level) for a regex-based transcription to be reliable and
// easy to verify by eye against the source.
//
// Output (src/lib/report/brand-mark.tsx) is committed, not gitignored —
// it's derived from a static brand asset that rarely changes, not a
// runtime-fetched binary. Re-run this manually if the source SVG changes.
//
// Usage: node scripts/generate-report-brand-mark.mjs
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.resolve(__dirname, "..");
const srcPath = path.join(
  projectRoot,
  "public",
  "logo",
  "statura_logo_on_light.svg",
);
const outPath = path.join(
  projectRoot,
  "src",
  "lib",
  "report",
  "brand-mark.tsx",
);

const svg = readFileSync(srcPath, "utf8");

function attr(str, name) {
  const m = str.match(new RegExp(`${name}="([^"]*)"`));
  return m ? m[1] : undefined;
}

// SVG kebab-case attribute -> react-pdf camelCase prop.
const ATTR_MAP = {
  "stroke-width": "strokeWidth",
  "stroke-linecap": "strokeLinecap",
  "stroke-linejoin": "strokeLinejoin",
};

function jsxAttrs(str, names) {
  return names
    .map((name) => {
      const value = attr(str, name);
      if (value === undefined) return null;
      const propName = ATTR_MAP[name] ?? name;
      return `${propName}="${value}"`;
    })
    .filter(Boolean)
    .join(" ");
}

const lines = [];

const rectMatch = svg.match(/<rect ([^>]*)\/>/);
if (rectMatch) {
  lines.push(`<Rect ${jsxAttrs(rectMatch[1], ["width", "height", "fill"])} />`);
}

const bodyStart = svg.indexOf("<rect");
const bodyEnd = svg.indexOf("</svg>");
const body = svg.slice(bodyStart, bodyEnd);

const elementRe =
  /<path ([^>]*)\/>|<circle ([^>]*)\/>|<line ([^>]*)\/>|<g transform="([^"]*)"><path ([^>]*)\/><\/g>/g;

let match = elementRe.exec(body);
while (match !== null) {
  if (match[1] !== undefined) {
    lines.push(`<Path ${jsxAttrs(match[1], ["d", "fill"])} />`);
  } else if (match[2] !== undefined) {
    lines.push(
      `<Circle ${jsxAttrs(match[2], ["cx", "cy", "r", "fill", "stroke", "stroke-width"])} />`,
    );
  } else if (match[3] !== undefined) {
    lines.push(
      `<Line ${jsxAttrs(match[3], ["x1", "y1", "x2", "y2", "stroke", "stroke-width", "stroke-linecap"])} />`,
    );
  } else if (match[4] !== undefined) {
    lines.push(
      `<G transform="${match[4]}"><Path ${jsxAttrs(match[5], ["d", "fill"])} /></G>`,
    );
  }
  match = elementRe.exec(body);
}

const viewBox = attr(svg.match(/<svg [^>]*>/)[0], "viewBox");

const output = `// GENERATED by scripts/generate-report-brand-mark.mjs from
// public/logo/statura_logo_on_light.svg — do not hand-edit; re-run the
// script instead if the source SVG changes.
import { Circle, G, Line, Path, Rect, Svg } from "@react-pdf/renderer";

export function BrandMark({ size = 32 }: { size?: number }) {
  return (
    <Svg viewBox="${viewBox}" width={size} height={size}>
      ${lines.join("\n      ")}
    </Svg>
  );
}
`;

writeFileSync(outPath, output);
console.log(
  `Wrote ${path.relative(projectRoot, outPath)} (${lines.length} elements)`,
);
