// P18 B.4: compile the Produktüberblick's Markdown into a generated module.
//
// Same approach, and the same reason, as the handbook (scripts/build-handbook.mjs):
// the Markdown in docs/ueberblick/de/** is the single source, and the app
// imports plain data rather than reading the filesystem at run time.
//
// Deliberately a second small script rather than a parameter on the handbook
// build: the two documents have different frontmatter (a section carries a
// screenshot, a chapter carries a part, a role list and a module) and sharing
// one builder would mean a union type that is wrong for both.
//
// Idempotent. CI runs it and fails if the generated file is not what the
// sources produce.
//
// Usage: npm run docs:overview
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const SOURCE_DIR = join(process.cwd(), "docs", "ueberblick", "de");
const OUT_FILE = join(process.cwd(), "src", "generated", "overview.ts");

function parseFrontmatter(raw, file) {
  const match = /^---\n([\s\S]*?)\n---\n?([\s\S]*)$/.exec(
    raw.replace(/\r\n/g, "\n"),
  );
  if (!match) throw new Error(`${file}: missing --- frontmatter block`);
  const meta = {};
  for (const line of match[1].split("\n")) {
    if (line.trim().length === 0) continue;
    const kv = /^([a-zA-Z]+):\s*(.*)$/.exec(line);
    if (!kv) throw new Error(`${file}: cannot parse frontmatter line: ${line}`);
    meta[kv[1]] = kv[2].trim();
  }
  return { meta, body: match[2].trim() };
}

const REQUIRED = ["title", "order", "screenshot"];

function main() {
  let files;
  try {
    files = readdirSync(SOURCE_DIR)
      .filter((f) => f.endsWith(".md"))
      .sort();
  } catch {
    console.error(`No overview sources at ${SOURCE_DIR}`);
    process.exit(1);
  }

  const sections = [];
  for (const file of files) {
    const raw = readFileSync(join(SOURCE_DIR, file), "utf8");
    const { meta, body } = parseFrontmatter(raw, file);
    for (const key of REQUIRED) {
      if (!meta[key]) throw new Error(`${file}: frontmatter is missing ${key}`);
    }
    sections.push({
      slug: file.replace(/^\d+-/, "").replace(/\.md$/, ""),
      title: meta.title,
      order: Number.parseInt(meta.order, 10),
      // "none" means no screenshot for this section, rather than a missing key.
      screenshot: meta.screenshot === "none" ? null : meta.screenshot,
      markdown: body,
    });
  }
  sections.sort((a, b) => a.order - b.order);

  const header = `// GENERATED by scripts/build-overview.mjs — do not edit.
// Source: docs/ueberblick/de/**. Run \`npm run docs:overview\` after a change.

export type OverviewSection = {
  slug: string;
  title: string;
  order: number;
  // File name inside docs/handbuch/img, or null for a section without one.
  screenshot: string | null;
  markdown: string;
};

export const OVERVIEW_SECTIONS: OverviewSection[] = ${JSON.stringify(sections, null, 2)};
`;

  mkdirSync(join(process.cwd(), "src", "generated"), { recursive: true });
  writeFileSync(OUT_FILE, header, "utf8");
  console.log(
    `overview: ${sections.length} section(s) → src/generated/overview.ts`,
  );
}

main();
